function t(key, vars) {
  const pack = I18N[state.uiLang] || I18N.zh;
  let s = pack[key];
  if (s === undefined) s = I18N.zh[key] !== undefined ? I18N.zh[key] : key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

function pickName(names) {
  if (!names) return '';
  return names[state.uiLang] || names.en || names.zh || names.ms || '';
}
